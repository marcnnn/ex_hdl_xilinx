defmodule ExHdlXilinx.Vivado.Tcl do
  @moduledoc """
  Non-project Tcl script for a `ExHdlXilinx.Vivado.Build`.

  Flow: read sources and constraints, `synth_design`, `opt_design`,
  `place_design`, optional `phys_opt_design`, `route_design`, checkpoints and
  reports in `out_dir`, `write_bitstream`, optional `write_cfgmem`. The
  paths in the spec are used as given (the runner stages them relative to the
  script).

      iex> b = ExHdlXilinx.Vivado.Build.new(name: "d", top: "top", part: "xcku3p-ffvb676-1-e", sources: ["src/top.sv"])
      iex> tcl = ExHdlXilinx.Vivado.Tcl.script(b)
      iex> tcl =~ "synth_design -top top -part xcku3p-ffvb676-1-e"
      true
      iex> tcl =~ "read_verilog -sv {src/top.sv}"
      true
  """

  alias ExHdlXilinx.Vivado.{Build, IP}

  @spec script(Build.t()) :: String.t()
  def script(%Build{} = b) do
    out = b.out_dir

    [
      "# Generated by ExHdlXilinx.Vivado.Tcl; do not edit",
      "set_param general.maxThreads #{b.jobs}",
      "file mkdir #{out}",
      "set_part #{b.part}",
      read_lines(b),
      ip_lines(b),
      b.pre_tcl,
      synth(b),
      "write_checkpoint -force #{out}/post_synth.dcp",
      "opt_design#{dir(b, :opt)}",
      "place_design#{dir(b, :place)}",
      if(b.phys_opt, do: "phys_opt_design#{dir(b, :phys_opt)}", else: []),
      "route_design#{dir(b, :route)}",
      "write_checkpoint -force #{out}/post_route.dcp",
      Enum.map(b.reports, &report(&1, out)),
      gate(b),
      bitstream(b),
      b.post_tcl,
      "puts \"ex_hdl_xilinx: build #{b.name} done\""
    ]
    |> List.flatten()
    |> Enum.join("\n")
    |> Kernel.<>("\n")
  end

  defp ip_lines(%Build{ips: []}), do: []

  defp ip_lines(%Build{ips: ips, out_dir: out}),
    do: ["file mkdir #{out}/ip" | Enum.flat_map(ips, &IP.tcl(&1, "#{out}/ip"))]

  defp read_lines(b) do
    generated = for {name, _} <- Enum.sort(b.generated), do: "src/#{name}"

    src =
      for f <- b.sources ++ generated do
        case Path.extname(f) do
          ".sv" -> "read_verilog -sv {#{f}}"
          ".svh" -> []
          ".v" -> "read_verilog {#{f}}"
          ".vh" -> []
          e when e in [".vhd", ".vhdl"] -> "read_vhdl -vhdl2008 {#{f}}"
          ".mem" -> "add_files -norecurse {#{f}}"
          other -> raise ArgumentError, "unsupported source type #{inspect(other)} (#{f})"
        end
      end

    xdc = for f <- b.xdc, do: "read_xdc {#{f}}"
    text = if b.xdc_text, do: ["read_xdc {constraints.xdc}"], else: []
    [src, xdc, text]
  end

  defp synth(b) do
    args =
      [
        "-top #{b.top}",
        "-part #{b.part}"
      ] ++
        opt_arg(b, :synth) ++
        for({k, v} <- Enum.sort(b.generics), do: "-generic #{k}=#{v}") ++
        for({k, v} <- Enum.sort(b.defines), do: "-verilog_define #{k}=#{v}")

    "synth_design " <> Enum.join(args, " ")
  end

  defp opt_arg(b, key), do: if(d = b.directives[key], do: ["-directive #{d}"], else: [])

  defp dir(b, key), do: if(d = b.directives[key], do: " -directive #{d}", else: "")

  defp report(:timing_summary, out),
    do:
      "report_timing_summary -delay_type min_max -report_unconstrained -max_paths 20 -file #{out}/timing_summary.rpt"

  defp report(:utilization, out), do: "report_utilization -file #{out}/utilization.rpt"
  defp report(:drc, out), do: "report_drc -file #{out}/drc.rpt"
  defp report(:methodology, out), do: "report_methodology -file #{out}/methodology.rpt"

  defp report(:clock_interaction, out),
    do: "report_clock_interaction -delay_type min_max -file #{out}/clock_interaction.rpt"

  defp report(:power, out), do: "report_power -file #{out}/power.rpt"
  defp report(:cdc, out), do: "report_cdc -details -file #{out}/cdc.rpt"

  defp gate(%Build{timing_gate: :ignore}), do: []

  defp gate(%Build{timing_gate: mode}) do
    action =
      if mode == :error,
        do: ~s|error "timing not met (WNS $wns ns, WHS $whs ns)"|,
        else:
          ~s|puts "CRITICAL WARNING: [ex_hdl_xilinx 1-1] timing not met (WNS $wns ns, WHS $whs ns)"|

    [
      "set wns [get_property SLACK [get_timing_paths -max_paths 1 -nworst 1 -setup]]",
      "set whs [get_property SLACK [get_timing_paths -max_paths 1 -nworst 1 -hold]]",
      "if {($wns ne \"\" && $wns < 0) || ($whs ne \"\" && $whs < 0)} { #{action} }"
    ]
  end

  defp bitstream(%Build{bitstream: false}), do: []

  defp bitstream(%Build{} = b) do
    bit = "#{b.out_dir}/#{b.name}.bit"

    [
      "write_bitstream -force #{bit}",
      case b.cfgmem do
        nil ->
          []

        c ->
          fmt = Map.get(c, :format, :mcs)
          addr = Map.get(c, :load_address, "0x0")

          "write_cfgmem -force -format #{fmt} -size #{c.size_mb} -interface #{c.interface} " <>
            ~s|-loadbit "up #{addr} #{bit}" #{b.out_dir}/#{b.name}.#{fmt}|
      end
    ]
  end
end
